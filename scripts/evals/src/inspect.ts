import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createClient } from '@arizeai/phoenix-client';
import { getExperimentInfo } from '@arizeai/phoenix-client/experiments';
import { report,type Result } from './core.js';
import { inspectResults } from './phoenix.js';
const root=fileURLToPath(new URL('../../../',import.meta.url));
if (!process.argv[2]) throw Error('Pass report directory relative to repository root');
const source=resolve(root,process.argv[2]);
const summary=JSON.parse(await readFile(`${source}/summary.json`,'utf8'));
const results:Result[]=(await readFile(`${source}/results.jsonl`,'utf8')).trim().split(/\r?\n/).map(line=>JSON.parse(line));
const baseUrl=process.env.PHOENIX_URL??'http://localhost:6006';
const client=createClient({options:{baseUrl}});
const experiment=await getExperimentInfo({client,experimentId:summary.metadata.experimentId});
if(experiment.missingRunCount!==0 || experiment.successfulRunCount+experiment.failedRunCount!==results.length)throw Error('Incomplete published experiment');
await inspectResults(results,baseUrl,summary.metadata.experimentProject);
const output=`${source}-verified`;
const verified=await report(output,results,{...summary.metadata,sourceReport:source,verifiedAt:new Date().toISOString()});
console.log(JSON.stringify({output,summary:verified.summary}));
