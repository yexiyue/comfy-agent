// Durable lifecycle smoke replaces the previous stateless HTTP request harness.
import { spawnSync } from 'node:child_process';
import { readFile,writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { createClient } from '@arizeai/phoenix-client';
import { getSpans } from '@arizeai/phoenix-client/spans';
const root=fileURLToPath(new URL('../../../',import.meta.url));
const matrix=spawnSync(process.execPath,['--experimental-strip-types',`${root}/scripts/durable-check/check.mjs`,'--phoenix'],{cwd:root,env:process.env,stdio:'inherit',windowsHide:true});assert.equal(matrix.status,0);
const evidence=JSON.parse(await readFile(`${root}/outputs/durable-check.json`,'utf8')) as {runId?:string;oldRun?:string;newRun?:string}[];
const ids=new Set(evidence.flatMap(e=>[e.runId,e.oldRun,e.newRun].filter((id):id is string=>!!id)));
const client=createClient({options:{baseUrl:process.env.PHOENIX_URL??'http://localhost:6006'}});
const spans=(await Promise.all([...ids].map(id=>getSpans({client,project:{projectName:process.env.PHOENIX_PROJECT_NAME??'comfy-agent-local'},name:'agent.run',attributes:{'agent.run_id':id},limit:100})))).flatMap(result=>result.spans);
const roots=spans.filter(span=>span.name==='agent.run' && ids.has(String(span.attributes?.['agent.run_id'])));
assert(new Set(roots.map(s=>s.attributes?.['agent.run_id'])).size>=ids.size-1,'Missing durable roots beyond the expected force-killed attempt');
assert(roots.some(s=>s.attributes?.['agent.outcome']==='paused'));assert(roots.some(s=>s.attributes?.['agent.outcome']==='shutdown'));
assert(roots.some(s=>s.attributes?.['agent.outcome']==='finished'));assert(roots.some(s=>s.attributes?.['agent.outcome']==='cancelled'));
for(const span of roots)assert(span.attributes?.['agent.attempt_id']);
await writeFile(`${root}/outputs/phoenix-smoke.json`,JSON.stringify({runs:ids.size,attempts:roots.length,outcomes:roots.map(s=>s.attributes?.['agent.outcome'])},null,2));
console.log('Phoenix durable lifecycle spans passed');
